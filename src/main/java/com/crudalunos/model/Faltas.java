public class Faltas {
   private Aluno objeto;
   private int numero;

    public Faltas(Aluno objeto) {
        this.objeto = objeto;
        this.numero = numero;
    }
   

    public Aluno getObjeto() {
        return objeto;
    }

    public void setObjeto(Aluno objeto) {
        this.objeto = objeto;
    }

    public int getNumero() {
        return numero;
    }

    public void setNumero(int numero) {
        this.numero = numero;
    }

   
    
}
