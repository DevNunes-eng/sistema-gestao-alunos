    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        Aluno alunoSelecionado = (Aluno) cmbAluno.getSelectedItem();
        List<String> anotacoes = alunoSelecionado.getInfo();

        if (!anotacoes.isEmpty()) {
            Object[] opcoes = anotacoes.toArray();
            String anotacaoSelecionada = (String) JOptionPane.showInputDialog(
                    null,
                    "Selecione uma anotação:",
                    "Editar ou Excluir Anotação",
                    JOptionPane.PLAIN_MESSAGE,
                    null,
                    opcoes,
                    opcoes[0]
            );

            if (anotacaoSelecionada != null) {
                int indice = anotacoes.indexOf(anotacaoSelecionada);

                String[] acoes = {"Editar", "Excluir", "Cancelar"};
                int escolha = JOptionPane.showOptionDialog(
                        null,
                        "O que você deseja fazer com essa anotação?",
                        "Ação",
                        JOptionPane.DEFAULT_OPTION,
                        JOptionPane.QUESTION_MESSAGE,
                        null,
                        acoes,
                        acoes[0]
                );

                if (escolha == 0) { // Editar
                    String novaAnotacao = JOptionPane.showInputDialog(
                            null,
                            "Edite a anotação:",
                            anotacaoSelecionada
                    );

                    if (novaAnotacao != null && !novaAnotacao.trim().isEmpty()) {
                        anotacoes.set(indice, novaAnotacao);
                        JOptionPane.showMessageDialog(null, "Anotação atualizada!");
                        try {
                            banco.exportarAlunos();
                        } catch (IOException ex) {
                            Logger.getLogger(TelaMudarInfo.class.getName()).log(Level.SEVERE, null, ex);
                        }
                    }

                } else if (escolha == 1) { // Excluir
                    anotacoes.remove(indice);
                    JOptionPane.showMessageDialog(null, "Anotação removida!");
                    try {
                        banco.exportarAlunos();
                    } catch (IOException ex) {
                        Logger.getLogger(TelaMudarInfo.class.getName()).log(Level.SEVERE, null, ex);
                    }
                }
            }
        } else {
            JOptionPane.showMessageDialog(null, "Este aluno não tem anotações.");
        }
    }

