    private void btnExibirActionPerformed(java.awt.event.ActionEvent evt) {
        Aluno objeto = (Aluno) cmbAluno.getSelectedItem();
        boolean achou = false;

        if (objeto != null) {
            String linha = "Id: " + objeto.getId() + "\n";
            txtLinha.append(linha);
            String linha4 = "Nascimento: " + objeto.getNascimento()+ "\n";
            txtLinha.append(linha4);

            for (String infos : objeto.getInfo()) {
                if(infos != null && !infos.trim().isEmpty()){
                    String linha5 = "- " + infos + "\n";
                    txtLinha.append(linha5);
                    achou = true;
                }
            }
            if(!achou){
                String linha8 = "Não há anotações desse aluno!\n";
                txtLinha.append(linha8);
            }
        } else {
            txtLinha.append("Aluno não encontrado.\n");
        }
    }

