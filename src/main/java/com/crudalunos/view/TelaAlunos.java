    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {
        if (banco.getListaAluno() == null || banco.getListaAluno().isEmpty()) {
            JOptionPane.showMessageDialog(
                    null,
                    "Erro! Não tem nenhum aluno cadastrado no sistema para salvar informações!",
                    "Atenção",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        try {
            banco.exportarAlunos();
        } catch (IOException ex) {
            Logger.getLogger(TelaAlunos.class.getName()).log(Level.SEVERE, null, ex);
        }
        try {
            banco.exportarTodasAsNotas();
        } catch (IOException ex) {
            Logger.getLogger(TelaAlunos.class.getName()).log(Level.SEVERE, null, ex);
        }
        JOptionPane.showMessageDialog(null, "Dados dos alunos foram salvos com sucesso!");
    }

