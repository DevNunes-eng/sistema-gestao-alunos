    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {
        // Exibe a janela de confirmação com a mensagem de alerta
        int confirmacao = JOptionPane.showConfirmDialog(
                this,
                "Tem certeza que deseja sair do sistema?\nNão se esqueça de salvar os dados antes de sair!",
                "Confirmação de Saída",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        // Verifica se o usuário clicou no botão "Sim" (cujo valor interno é 0)
        if (confirmacao == JOptionPane.YES_OPTION) {
            System.exit(0); // Só encerra o programa se ele confirmar
        }
        // Se ele clicar em "Não" ou fechar a janelinha, nada acontece e ele volta para o sistema.
    }

