    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {
        String nome = txtNome.getText();
        String idz = txtId.getText();
        String nascimento = txtNasci.getText();

        boolean idCadastrado = false;
        if (nome.isEmpty() || idz.isEmpty() || nascimento.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Por favor, preencha todos os campos!");
            return;
        }
        if(!BancoDeDados.validarID(txtId.getText())){
            JOptionPane.showMessageDialog(null, "Formato de ID Errado! Digite um número inteiro!");
            return;
        }
        if(!BancoDeDados.validarNascimento(nascimento)){
            JOptionPane.showMessageDialog(null, "Formato de nascimento errado! Digite no formato **/**/****");
            return;
        }

        int id = Integer.parseInt(txtId.getText());

        ArrayList<Aluno> alunos = banco.getListaAluno();
        for (int i = 0; i < alunos.size(); i++) {
            Aluno objeto = alunos.get(i);

            if(id == objeto.getId()){
                idCadastrado = true;
                break;
            }
        }

        if(idCadastrado){
            JOptionPane.showMessageDialog(null, "ID já cadastrado! Digite um novo ID!");
            txtId.setText("");
        }
        else{
            Aluno objeto1 = new Aluno(nome, id, nascimento);

            banco.Addconta(objeto1);
            JOptionPane.showMessageDialog(null,"Aluno Cadastrado com sucesso!");

            try {
                banco.exportarAlunos();
                dispose();
            } catch (IOException ex) {
                Logger.getLogger(TelaCadastro.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }

