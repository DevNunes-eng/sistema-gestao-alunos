    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {
        if(C1.isSelected()){
            JOptionPane.showMessageDialog(null,"Falta adicionada!");

            Aluno objeto = (Aluno) cmbAluno.getSelectedItem();
            objeto.adicionarFalta(1); // Passa o aluno atual para o construtor de Faltas
            C1.setSelected(false);
            try {
                banco.exportarAlunos();
            } catch (IOException ex) {
                Logger.getLogger(TelaFaltas.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }

    private void btnExibirActionPerformed(java.awt.event.ActionEvent evt) {
        if (cmbAluno.getSelectedItem() == null){
            JOptionPane.showMessageDialog(
                    null,
                    "Atenção: Nenhum aluno foi selecionado!",
                    "Aviso",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        Aluno objeto = (Aluno) cmbAluno.getSelectedItem();
        List<Integer> faltas = objeto.getFaltas();

        int totalFaltas = 0;
        if (faltas != null && !faltas.isEmpty()) {
            totalFaltas = faltas.get(0);  // pega o total guardado no índice 0
        }

        String Linha = "Número de faltas do aluno " + objeto.getNome() + " são: " + totalFaltas;
        txtLinha.setText(Linha + "\n");
    }

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        if(C1.isSelected()){
            JOptionPane.showMessageDialog(null,"Falta removida!"); // Corrigido a mensagem

            Aluno objeto = (Aluno) cmbAluno.getSelectedItem();
            objeto.removerFalta(1); // Passa o aluno atual para o construtor de Faltas
            C1.setSelected(false);
            try {
                banco.exportarAlunos();
            } catch (IOException ex) {
                Logger.getLogger(TelaFaltas.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }

