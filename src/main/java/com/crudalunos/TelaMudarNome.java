    private void btnMudarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMudarActionPerformed
        Aluno alunoSelecionado = banco.getObjeto();
        String nome = txtNovonome.getText();
        alunoSelecionado.setNome(nome);
        disci = alunoSelecionado.getDisci();
        for(int i=0;i<disci.size();i++){
            Disciplinas disciplina = disci.get(i);
            disciplina.setAluno(alunoSelecionado);
            
        }
    
       
       
        
        try {
            banco.exportarAlunos();
        } catch (IOException ex) {
            Logger.getLogger(TelaMudarNome.class.getName()).log(Level.SEVERE, null, ex);
        }
        JOptionPane.showMessageDialog(null, "Nome alterado com sucesso!");
        try {
            banco.exportarTodasAsNotas();
        } catch (IOException ex) {
            Logger.getLogger(TelaMudarNome.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnMudarActionPerformed

